const EVERY_DAY = [true, true, true, true, true, true, true];

const win = (id: string, label: string, start: string, end: string): TimeWindow => ({ id, label, start, end });

/** A Monday → Sunday week with the days `offsets` from today switched on, so the sample fits any weekday. */
function daysFromToday(...offsets: number[]): boolean[] {
  const today = (new Date().getDay() + 6) % 7;
  const days = [false, false, false, false, false, false, false];
  for (const o of offsets) days[(today + o) % 7] = true;
  return days;
}

function member(
  id: string,
  name: string,
  relation: string,
  role: FamilyMember['role'],
  focus: string,
  skills: Skill[],
  windows: TimeWindow[],
  access: Partial<FamilyMember['access']> = {},
  extra: Partial<FamilyMember> = {},
): FamilyMember {
  return {
    id,
    name,
    relation,
    role,
    focus,
    email: `${name.split(' ')[0].toLowerCase()}@example.com`,
    status: 'active',
    skills,
    availability: { days: EVERY_DAY, windows },
    access: { schedule: true, medical: false, documents: true, ...access },
    joinedAt: at(-200, '10:00'),
    ...extra,
  };
}

function weekly(
  id: string,
  memberId: string,
  title: string,
  kind: PersonalEvent['kind'],
  time: string,
  durationMin: number,
  days: boolean[],
  location: string,
  visibility: PersonalEvent['visibility'] = 'details',
): PersonalEvent {
  return { id, memberId, title, kind, start: at(-28, time), durationMin, repeat: 'weekly', days, location, visibility, createdAt: at(-30, '09:00') };
}

